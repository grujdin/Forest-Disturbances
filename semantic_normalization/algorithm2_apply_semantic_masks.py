def load_scene_inventory_with_recommendations() -> pd.DataFrame:
    """Load cache inventory and attach recommendations from the Algorithm #1 envelope bundle.

    The envelope bundle is treated as the source of truth for scene eligibility.
    Cache-side recommendation columns are retained with a ``cache_`` prefix when
    they differ from the bundle columns.
    """
    inv = pd.read_csv(require_cache_file(CACHE_ROOT / "scene_inventory.csv"))
    inv["scene"] = inv["scene"].astype(str)
    rec = load_scene_recommendations()

    for col in ["recommendation", "recommendation_reason"]:
        if col in inv.columns:
            inv = inv.rename(columns={col: f"cache_{col}"})

    rec_cols = [c for c in ["scene", "recommendation", "recommendation_reason", "clear_frac", "veg_frac", "cloud_frac", "snow_frac", "shadow_frac", "scl7_frac"] if c in rec.columns]
    merged = inv.merge(rec[rec_cols], on="scene", how="left", suffixes=("", "_rec"))
    if "recommendation" not in merged.columns:
        merged["recommendation"] = merged.get("cache_recommendation", "missing")
    if "recommendation_reason" not in merged.columns:
        merged["recommendation_reason"] = merged.get("cache_recommendation_reason", "")
    merged["recommendation"] = merged["recommendation"].astype(str).str.lower().str.strip()
    return merged


def filename_quality_score(scene_name: str) -> float:
    s = str(scene_name).lower()
    score = 0.0
    if "no_cloud" in s or "no-cloud" in s or "nocloud" in s:
        score += 100.0
    if "verylow" in s or "very_low" in s:
        score += 50.0
    if "low_cloud" in s or "low-cloud" in s or "lowcloud" in s:
        score += 20.0
    if "lowmedium" in s or "medium" in s:
        score -= 20.0
    if "high_cloud" in s or "high-cloud" in s or "highcloud" in s:
        score -= 80.0
    if "snow" in s or "winter" in s:
        score -= 100.0
    return score


def filter_inventory_by_recommendation(inv: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame]:
    if not FILTER_TARGET_SCENES_TO_ENVELOPE_POLICY:
        out = inv.copy()
        out["included_by_recommendation"] = True
        out["allowed_recommendations"] = "filter disabled"
        out["filter_policy"] = ENVELOPE_RUN
        out["filter_reason"] = "scene filtering disabled"
        return out, out.copy()

    allowed = allowed_recommendations_for_envelope_run(ENVELOPE_RUN)
    log_rows = []
    included_flags = []
    for row in inv.itertuples(index=False):
        rec = str(getattr(row, "recommendation", "missing")).lower().strip()
        if rec in {"", "nan", "none"}:
            rec = "missing"
        if rec == "missing":
            include = not EXCLUDE_SCENES_WITHOUT_RECOMMENDATION
            reason = "not found in scene_blacklist_recommendation.csv"
        else:
            include = rec in allowed
            reason = str(getattr(row, "recommendation_reason", ""))
        included_flags.append(include)
        log_rows.append({
            "scene": row.scene,
            "scene_key": getattr(row, "scene_key", ""),
            "date": getattr(row, "date", ""),
            "recommendation": rec,
            "included_by_recommendation": include,
            "allowed_recommendations": ";".join(sorted(allowed)),
            "filter_policy": ENVELOPE_RUN,
            "filter_reason": reason,
            "clear_frac": getattr(row, "clear_frac", np.nan) if hasattr(row, "clear_frac") else np.nan,
            "scl_available": getattr(row, "scl_available", np.nan) if hasattr(row, "scl_available") else np.nan,
            "scl_used": getattr(row, "scl_used", np.nan) if hasattr(row, "scl_used") else np.nan,
        })
    eligibility = pd.DataFrame(log_rows)
    out = inv.loc[included_flags].copy().reset_index(drop=True)
    return out, eligibility


def deduplicate_inventory_by_date(inv: pd.DataFrame, eligibility: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame]:
    eligibility = eligibility.copy()
    eligibility["included_after_date_dedup"] = eligibility["included_by_recommendation"].astype(bool)
    eligibility["duplicate_date_selected"] = False
    if not DEDUPLICATE_TARGET_SCENES_BY_DATE or inv.empty:
        eligibility["included"] = eligibility["included_after_date_dedup"]
        return inv, eligibility

    kept_rows = []
    for date, sub in inv.groupby("date", dropna=False):
        if len(sub) == 1:
            chosen = sub.iloc[0]
        else:
            temp = sub.copy()
            for col in ["clear_frac", "veg_frac", "cloud_frac", "snow_frac", "shadow_frac", "scl7_frac"]:
                if col not in temp.columns:
                    temp[col] = np.nan
            temp["filename_quality_score"] = temp["scene"].map(filename_quality_score)
            temp["_clear_sort"] = pd.to_numeric(temp["clear_frac"], errors="coerce").fillna(-1.0)
            temp["_veg_sort"] = pd.to_numeric(temp["veg_frac"], errors="coerce").fillna(-1.0)
            temp["_cloud_sort"] = pd.to_numeric(temp["cloud_frac"], errors="coerce").fillna(1.0)
            temp["_snow_sort"] = pd.to_numeric(temp["snow_frac"], errors="coerce").fillna(1.0)
            temp = temp.sort_values(
                ["filename_quality_score", "_clear_sort", "_veg_sort", "_cloud_sort", "_snow_sort", "scene"],
                ascending=[False, False, False, True, True, True],
            )
            chosen = temp.iloc[0]
        kept_rows.append(chosen)

        date_mask = eligibility["date"].astype(str).eq(str(date)) & eligibility["included_by_recommendation"].astype(bool)
        chosen_mask = eligibility["scene"].astype(str).eq(str(chosen["scene"]))
        eligibility.loc[date_mask, "included_after_date_dedup"] = False
        eligibility.loc[chosen_mask, "included_after_date_dedup"] = True
        eligibility.loc[chosen_mask, "duplicate_date_selected"] = True
        dropped_mask = date_mask & (~chosen_mask)
        if dropped_mask.any():
            eligibility.loc[dropped_mask, "filter_reason"] = (
                eligibility.loc[dropped_mask, "filter_reason"].astype(str)
                + f"; duplicate acquisition date {date}; selected {chosen['scene']}"
            )

    kept = pd.DataFrame(kept_rows).sort_values(["date", "scene"]).reset_index(drop=True)
    eligibility["included"] = eligibility["included_after_date_dedup"]
    return kept, eligibility


def build_envelope_lookup(env: pd.DataFrame) -> Dict[Tuple[str, str, str], pd.Series]:
    return {
        (str(row["group_code"]), str(row["index"]), str(row["doy_bin_label"])): row
        for _, row in env.iterrows()
    }


def lookup_envelope_rows(
    env: pd.DataFrame,
    env_lookup: Dict[Tuple[str, str, str], pd.Series],
    group_code: str,
    target_bin_label: str,
    indices: List[str],
) -> Tuple[Dict[str, pd.Series], List[dict]]:
    out: Dict[str, pd.Series] = {}
    logs: List[dict] = []
    group_env = env[env["group_code"] == group_code]
    target_center = doy_bin_center_from_label(target_bin_label)
    for idx in indices:
        exact_key = (str(group_code), str(idx), str(target_bin_label))
        row = env_lookup.get(exact_key)
        if row is not None:
            out[idx] = row
            logs.append({
                "group_code": group_code,
                "index": idx,
                "requested_bin": target_bin_label,
                "used_bin": row["doy_bin_label"],
                "fallback_used": False,
            })
            continue
        subset = group_env[group_env["index"] == idx]
        if USE_NEAREST_BIN_FALLBACK and len(subset) > 0:
            temp = subset.copy()
            temp["bin_distance"] = (temp["doy_bin_center"] - target_center).abs()
            row = temp.sort_values(["bin_distance", "n_dates", "support_pixels_total"], ascending=[True, False, False]).iloc[0]
            out[idx] = row
            logs.append({
                "group_code": group_code,
                "index": idx,
                "requested_bin": target_bin_label,
                "used_bin": row["doy_bin_label"],
                "fallback_used": True,
            })
        else:
            raise KeyError(f"No envelope found for group={group_code}, index={idx}, bin={target_bin_label}")
    return out, logs



