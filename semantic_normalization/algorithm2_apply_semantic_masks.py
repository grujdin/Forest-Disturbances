def _as_bool(value) -> bool:
    if isinstance(value, (bool, np.bool_)):
        return bool(value)
    if pd.isna(value):
        return False
    return str(value).strip().lower() in {"1", "true", "yes", "y"}


def classify_envelope_confidence_from_values(n_unique_dates, support_pixels_total) -> dict:
    """Classify support when an older envelope table lacks confidence fields."""
    try:
        n_unique_dates = int(n_unique_dates)
    except Exception:
        n_unique_dates = 0
    try:
        support_pixels_total = int(support_pixels_total)
    except Exception:
        support_pixels_total = 0

    if n_unique_dates <= 0 or support_pixels_total <= 0:
        code = 4
        label = "missing"
    elif n_unique_dates >= ENVELOPE_CONFIDENCE_HIGH_MIN_UNIQUE_DATES:
        code = 1
        label = "high"
    elif (
        n_unique_dates >= ENVELOPE_CONFIDENCE_MEDIUM_MIN_UNIQUE_DATES
        and support_pixels_total >= MIN_SUPPORT_PIXELS_TOTAL_FOR_MEDIUM_CONFIDENCE
    ):
        code = 2
        label = "medium"
    else:
        code = 3
        label = "low"

    low_temporal = n_unique_dates < ENVELOPE_CONFIDENCE_MEDIUM_MIN_UNIQUE_DATES
    low_pixel = support_pixels_total < MIN_SUPPORT_PIXELS_TOTAL_FOR_MEDIUM_CONFIDENCE
    reasons = []
    if low_temporal:
        reasons.append(f"unique_dates<{ENVELOPE_CONFIDENCE_MEDIUM_MIN_UNIQUE_DATES}")
    if low_pixel:
        reasons.append(f"support_pixels_total<{MIN_SUPPORT_PIXELS_TOTAL_FOR_MEDIUM_CONFIDENCE}")
    if not reasons:
        reasons.append("sufficient_support")
    return {
        "envelope_confidence": label,
        "envelope_confidence_code": code,
        "low_support_flag": bool(label in {"low", "missing"}),
        "low_temporal_support_flag": bool(low_temporal),
        "support_pixels_total_low_flag": bool(low_pixel),
        "confidence_reason": ";".join(reasons),
    }


def ensure_envelope_confidence_columns(env: pd.DataFrame) -> pd.DataFrame:
    """Ensure Phase 4 confidence columns exist for both new and older envelope tables."""
    env = env.copy()
    if "n_unique_dates" not in env.columns:
        env["n_unique_dates"] = env.get("n_dates", np.nan)
    if "n_scene_records" not in env.columns:
        env["n_scene_records"] = env.get("n_dates", np.nan)
    if "operational_width" not in env.columns and {ENVELOPE_LOW_COL, ENVELOPE_HIGH_COL}.issubset(env.columns):
        env["operational_width"] = pd.to_numeric(env[ENVELOPE_HIGH_COL], errors="coerce") - pd.to_numeric(env[ENVELOPE_LOW_COL], errors="coerce")

    metas = [
        classify_envelope_confidence_from_values(row.get("n_unique_dates", row.get("n_dates", np.nan)), row.get("support_pixels_total", np.nan))
        for _, row in env.iterrows()
    ]
    for col in [
        "envelope_confidence",
        "envelope_confidence_code",
        "low_support_flag",
        "low_temporal_support_flag",
        "support_pixels_total_low_flag",
        "confidence_reason",
    ]:
        if col not in env.columns:
            env[col] = [m[col] for m in metas]
        else:
            missing = env[col].isna() | env[col].astype(str).str.strip().isin(["", "nan", "None"])
            if missing.any():
                fill_values = pd.Series([m[col] for m in metas], index=env.index)
                env.loc[missing, col] = fill_values.loc[missing]
    return env


def confidence_from_row(row: pd.Series) -> str:
    value = str(row.get("envelope_confidence", "unknown")).strip().lower()
    if value in ENVELOPE_CONFIDENCE_VALUES:
        return value
    meta = classify_envelope_confidence_from_values(row.get("n_unique_dates", row.get("n_dates", np.nan)), row.get("support_pixels_total", np.nan))
    return str(meta["envelope_confidence"])


def confidence_code_from_row(row: pd.Series) -> int:
    try:
        code = int(row.get("envelope_confidence_code"))
        if code in {1, 2, 3, 4}:
            return code
    except Exception:
        pass
    return ENVELOPE_CONFIDENCE_VALUES.get(confidence_from_row(row), ENVELOPE_CONFIDENCE_VALUES["unknown"])


def worst_confidence(confidences: List[str]) -> str:
    """Return the weakest confidence label, where low/missing is weaker than medium/high."""
    if not confidences:
        return "unknown"
    severity = {"high": 1, "medium": 2, "low": 3, "missing": 4, "unknown": 4}
    inv = {1: "high", 2: "medium", 3: "low", 4: "unknown"}
    return inv.get(max(severity.get(str(c).lower(), 4) for c in confidences), "unknown")


def _row_value(row: pd.Series, col: str, default=np.nan):
    return row[col] if col in row.index else default


def load_envelopes() -> pd.DataFrame:
    if ENVELOPE_SOURCE.suffix.lower() == ".zip":
        with zipfile.ZipFile(ENVELOPE_SOURCE, "r") as zf:
            with zf.open(ENVELOPE_CSV_IN_ZIP) as f:
                env = pd.read_csv(io.BytesIO(f.read()))
    else:
        env = pd.read_csv(ENVELOPE_SOURCE)

    if "doy_bin_center" not in env.columns:
        env["doy_bin_center"] = env["doy_bin_label"].apply(doy_bin_center_from_label)

    env = ensure_envelope_confidence_columns(env)

    if USE_ALL_FOREST_FALLBACK_FOR_UNKNOWN and ALL_FOREST_FALLBACK_CODE not in set(env["group_code"].astype(str)):
        num_cols = [c for c in env.columns if c not in {"group_code", "group_label", "index", "doy_bin_label"}]
        agg = {c: "median" for c in num_cols if pd.api.types.is_numeric_dtype(env[c])}
        af = env.groupby(["index", "doy_bin_label"], as_index=False).agg(agg)
        af["group_code"] = ALL_FOREST_FALLBACK_CODE
        af["group_label"] = ALL_FOREST_FALLBACK_LABEL
        if "doy_bin_center" not in af.columns:
            af["doy_bin_center"] = af["doy_bin_label"].apply(doy_bin_center_from_label)
        af = ensure_envelope_confidence_columns(af)
        af = af.reindex(columns=env.columns)
        env = pd.concat([env, af], ignore_index=True)
    return ensure_envelope_confidence_columns(env)


def allowed_recommendations_for_envelope_run(run: str) -> Set[str]:
    run = run.lower().strip()
    if run == "none":
        return {"keep", "caution", "blacklist"}
    if run == "blacklist":
        return {"keep", "caution"}
    if run == "blacklist_and_caution":
        return {"keep"}
    raise ValueError(f"Unsupported ENVELOPE_RUN: {run!r}")


