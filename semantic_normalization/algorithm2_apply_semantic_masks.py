def resolve_s1_descriptors_to_summarize(s1_row: pd.Series, s1_stack: Dict[str, np.ndarray]) -> List[str]:
    cfg = S1_DESCRIPTORS_TO_SUMMARIZE
    if isinstance(cfg, str) and cfg.lower().strip() == "auto":
        found = []
        txt = str(s1_row.get("descriptor_bands_available", ""))
        for name in [x.strip() for x in txt.split(",") if x.strip()]:
            if name not in found and name not in S1_DESCRIPTOR_EXCLUDE_FROM_SUMMARY:
                found.append(name)
        if not found:
            for name, arr in s1_stack.items():
                if name in S1_DESCRIPTOR_EXCLUDE_FROM_SUMMARY:
                    continue
                if arr is not None and np.isfinite(arr).any():
                    found.append(name)
        return found
    return [str(x) for x in cfg if str(x) not in S1_DESCRIPTOR_EXCLUDE_FROM_SUMMARY]


def summarize_nearest_s1_for_scene(
    scene_date: pd.Timestamp,
    semantic_domain: np.ndarray,
    group_raster: np.ndarray,
    group_lut_records: Dict[int, dict],
    group_profile: dict,
    out_scene_dir: Path,
) -> Tuple[dict, pd.DataFrame]:
    """Summarize nearest-date Sentinel-1 descriptors over the Algorithm #2 domain."""
    meta = {
        "s1_descriptor_summary_enabled": bool(ENABLE_S1_DESCRIPTOR_SUMMARIES),
        "s1_scene_used": "",
        "s1_date_used": "",
        "s1_abs_offset_days": np.nan,
        "s1_descriptor_stack_path": "",
        "s1_descriptor_available": False,
    }
    if not ENABLE_S1_DESCRIPTOR_SUMMARIES:
        return meta, pd.DataFrame()
    inv = get_s1_inventory_cached()
    if inv.empty:
        return meta, pd.DataFrame()
    s1_row = find_nearest_s1_scene(inv, scene_date, S1_MAX_ABS_DATE_OFFSET_DAYS)
    if s1_row is None:
        return meta, pd.DataFrame()
    stack_path = Path(str(s1_row.get("s1_stack_path", "")))
    valid_path = Path(str(s1_row.get("s1_valid_mask_path", "")))
    if not stack_path.exists() or not valid_path.exists():
        return meta, pd.DataFrame()
    try:
        s1_stack, s1_profile = read_float32_stack(stack_path, expected_names=S1_DESCRIPTOR_BANDS)
    except Exception:
        s1_stack, s1_profile = read_float32_stack(stack_path)
    s1_descriptors_to_summarize = resolve_s1_descriptors_to_summarize(s1_row, s1_stack)
    s1_valid_arr, s1_valid_profile = read_uint8_mask(valid_path)
    if not same_grid(s1_profile, group_profile) or not same_grid(s1_valid_profile, group_profile):
        raise RuntimeError(f"Sentinel-1 descriptor grid does not match semantic-mask grid: {stack_path}")
    s1_valid = s1_valid_arr == 1
    rows = []
    for gid, info in group_lut_records.items():
        mask_g = semantic_domain & (group_raster == int(gid)) & s1_valid
        if not np.any(mask_g):
            continue
        row = {
            "group_id": int(gid),
            "group_code": info.get("group_code", ""),
            "group_label": info.get("group_label", ""),
            "semantic_domain_s1_valid_px": int(mask_g.sum()),
        }
        row.update(summarize_stack_on_mask(s1_stack, mask_g, s1_descriptors_to_summarize))
        rows.append(row)
    out_df = pd.DataFrame(rows)
    if not out_df.empty:
        out_df.insert(0, "s1_abs_offset_days", int(s1_row.get("abs_offset_days", abs((pd.Timestamp(s1_row['date']) - scene_date).days))))
        out_df.insert(0, "s1_date", pd.Timestamp(s1_row["date"]).date().isoformat())
        out_df.insert(0, "s1_scene", str(s1_row["scene"]))
        out_df.to_csv(out_scene_dir / "s1_scene_descriptor_summary.csv", index=False)
    meta.update({
        "s1_scene_used": str(s1_row.get("scene", "")),
        "s1_date_used": pd.Timestamp(s1_row["date"]).date().isoformat(),
        "s1_abs_offset_days": int(s1_row.get("abs_offset_days", abs((pd.Timestamp(s1_row['date']) - scene_date).days))),
        "s1_descriptor_stack_path": str(stack_path),
        "s1_descriptor_available": True,
        "s1_descriptors_summarized": ",".join(s1_descriptors_to_summarize),
    })
    return meta, out_df


def process_cached_scene(
    scene_row: pd.Series,
    env: pd.DataFrame,
    env_lookup: Dict[Tuple[str, str, str], pd.Series],
    group_raster: np.ndarray,
    group_profile: dict,
    group_lut: pd.DataFrame,
) -> Tuple[dict, pd.DataFrame, pd.DataFrame]:
    scene = str(scene_row["scene"])
    scene_key = str(scene_row.get("scene_key", scene_row.get("scene_stem", scene)))
    scene_date = pd.Timestamp(scene_row["date"])
    scene_doy = int(scene_row["doy"])
    bin_label = doy_bin_label(scene_doy, DOY_BIN_WIDTH)

    clear_arr, clear_profile = read_uint8_mask(require_cache_file(Path(scene_row["clear_mask_path"])))
    if not same_grid(clear_profile, group_profile):
        raise RuntimeError(f"Clear mask grid does not match all-FMU group raster for {scene}")
    idx, idx_profile = read_float32_stack(require_cache_file(Path(scene_row["index_stack_path"])), expected_names=ALL_INDEX_STACK_BANDS)
    if not same_grid(idx_profile, group_profile):
        raise RuntimeError(f"Index stack grid does not match all-FMU group raster for {scene}")

    all_used_indices = CORE_INDICES + [x for x in OPTIONAL_INDICES if x not in CORE_INDICES]
    inside_by_index = {name: np.zeros(group_raster.shape, dtype=bool) for name in all_used_indices}
    vote_count = np.zeros(group_raster.shape, dtype=np.uint8)
    anomaly_sum = np.zeros(group_raster.shape, dtype=np.float32)
    anomaly_count = np.zeros(group_raster.shape, dtype=np.uint8)
    confidence_code_raw = np.full(group_raster.shape, 255, dtype=np.uint8)
    group_confidence_meta: Dict[int, dict] = {}
    clear_mask = clear_arr == 1
    grouped_valid = clear_mask & (group_raster > 0)

    group_lut_records = {
        int(r.group_id): {"group_code": r.group_code, "group_label": r.group_label}
        for r in group_lut[["group_id", "group_code", "group_label"]].itertuples(index=False)
    }

    lookup_logs: List[dict] = []
    for gid, meta in group_lut_records.items():
        group_code = meta["group_code"]
        mask_g = grouped_valid & (group_raster == gid)
        if not np.any(mask_g):
            continue
        rows_by_index, logs = lookup_envelope_rows(env, env_lookup, group_code, bin_label, all_used_indices)
        lookup_logs.extend(logs)

        core_confidences = [confidence_from_row(rows_by_index[name]) for name in CORE_INDICES]
        core_confidence = worst_confidence(core_confidences)
        group_confidence_meta[int(gid)] = {
            "core_envelope_confidence": core_confidence,
            "core_envelope_confidence_code": ENVELOPE_CONFIDENCE_VALUES.get(core_confidence, ENVELOPE_CONFIDENCE_VALUES["unknown"]),
            "core_low_confidence_lookup_count": int(sum(c == "low" for c in core_confidences)),
            "core_medium_confidence_lookup_count": int(sum(c == "medium" for c in core_confidences)),
            "core_high_confidence_lookup_count": int(sum(c == "high" for c in core_confidences)),
            "core_missing_or_unknown_confidence_lookup_count": int(sum(c in {"missing", "unknown"} for c in core_confidences)),
        }
        confidence_code_raw[mask_g] = np.uint8(ENVELOPE_CONFIDENCE_VALUES.get(core_confidence, ENVELOPE_CONFIDENCE_VALUES["unknown"]))

        for name in all_used_indices:
            low = float(rows_by_index[name][ENVELOPE_LOW_COL])
            high = float(rows_by_index[name][ENVELOPE_HIGH_COL])
            arr = idx[name]
            finite = mask_g & np.isfinite(arr)
            ok = finite & (arr >= low) & (arr <= high)
            inside_by_index[name][ok] = True

            if WRITE_ANOMALY_SCORE and name in CORE_INDICES:
                width = max(float(high - low), ANOMALY_EPS)
                dist = np.zeros(arr.shape, dtype=np.float32)
                below = finite & (arr < low)
                above = finite & (arr > high)
                dist[below] = ((low - arr[below]) / width).astype(np.float32)
                dist[above] = ((arr[above] - high) / width).astype(np.float32)
                anomaly_sum[finite] += dist[finite]
                anomaly_count[finite] += 1

    for name in CORE_INDICES:
        vote_count = vote_count + inside_by_index[name].astype(np.uint8)

    finite_core = np.ones(group_raster.shape, dtype=bool)
    for name in CORE_INDICES:
        finite_core &= np.isfinite(idx[name])
    semantic_domain = grouped_valid & finite_core

    keep = semantic_domain & (vote_count >= KEEP_VOTES_REQUIRED)
    drop = semantic_domain & (~keep)

    if DEDUPLICATE_TARGET_SCENES_BY_DATE:
        out_scene_dir = OUTPUT_DIR / scene_date.strftime("%Y-%m-%d")
    else:
        out_scene_dir = OUTPUT_DIR / scene_key
    out_scene_dir.mkdir(parents=True, exist_ok=True)

    # Sentinel-1 summaries are computed later after the semantic domain is known.

    keep_u8 = np.full(group_raster.shape, 255, dtype=np.uint8)
    keep_u8[semantic_domain] = 0
    keep_u8[keep] = 1
    write_uint8_mask(out_scene_dir / "semantic_keep_mask.tif", keep_u8, group_profile)

    drop_u8 = np.full(group_raster.shape, 255, dtype=np.uint8)
    drop_u8[semantic_domain] = 0
    drop_u8[drop] = 1
    write_uint8_mask(out_scene_dir / "semantic_drop_mask.tif", drop_u8, group_profile)

    votes_u8 = np.full(group_raster.shape, 255, dtype=np.uint8)
    votes_u8[semantic_domain] = vote_count[semantic_domain]
    write_uint8_mask(out_scene_dir / "semantic_vote_count.tif", votes_u8, group_profile)

    write_int16(out_scene_dir / "semantic_group_id.tif", group_raster.astype(np.int16), group_profile, nodata=-32768)

    anomaly_score = None
    if WRITE_ANOMALY_SCORE:
        anomaly_score = np.full(group_raster.shape, ANOMALY_SCORE_NODATA, dtype=np.float32)
        valid_anom = semantic_domain & (anomaly_count > 0)
        anomaly_score[valid_anom] = anomaly_sum[valid_anom] / anomaly_count[valid_anom].astype(np.float32)
        write_float32(out_scene_dir / "semantic_anomaly_score.tif", anomaly_score, group_profile, nodata=ANOMALY_SCORE_NODATA)

    if WRITE_ENVELOPE_CONFIDENCE_MASK:
        confidence_u8 = np.full(group_raster.shape, 255, dtype=np.uint8)
        confidence_u8[semantic_domain] = confidence_code_raw[semantic_domain]
        write_uint8_mask(out_scene_dir / "semantic_envelope_confidence.tif", confidence_u8, group_profile)

    if WRITE_INDEX_INSIDE_MASKS:
        for name in all_used_indices:
            arr = np.full(group_raster.shape, 255, dtype=np.uint8)
            arr[semantic_domain] = 0
            arr[inside_by_index[name] & semantic_domain] = 1
            write_uint8_mask(out_scene_dir / f"inside_{name.lower()}_envelope.tif", arr, group_profile)

    group_rows = []
    for gid, meta in group_lut_records.items():
        mask_g = semantic_domain & (group_raster == gid)
        if not np.any(mask_g):
            continue
        keep_g = keep & (group_raster == gid)
        drop_g = drop & (group_raster == gid)
        row = {
            "scene": scene,
            "scene_key": scene_key,
            "date": scene_date.date().isoformat(),
            "doy": scene_doy,
            "doy_bin_label": bin_label,
            "group_id": gid,
            "group_code": meta["group_code"],
            "group_label": meta["group_label"],
            "semantic_domain_px": int(mask_g.sum()),
            "keep_px": int(keep_g.sum()),
            "drop_px": int(drop_g.sum()),
            "keep_pct": float(100.0 * keep_g.sum() / mask_g.sum()),
            "mean_vote_count": float(vote_count[mask_g].mean()),
            **group_confidence_meta.get(int(gid), {
                "core_envelope_confidence": "unknown",
                "core_envelope_confidence_code": ENVELOPE_CONFIDENCE_VALUES["unknown"],
                "core_low_confidence_lookup_count": 0,
                "core_medium_confidence_lookup_count": 0,
                "core_high_confidence_lookup_count": 0,
                "core_missing_or_unknown_confidence_lookup_count": len(CORE_INDICES),
            }),
        }
        if anomaly_score is not None:
            row["mean_anomaly_score"] = float(np.nanmean(np.where(mask_g, anomaly_score, np.nan)))
        for name in all_used_indices:
            row[f"inside_{name.lower()}_pct"] = float(100.0 * inside_by_index[name][mask_g].mean())
        group_rows.append(row)
    group_df = pd.DataFrame(group_rows)

    s1_scene_meta, s1_group_df = summarize_nearest_s1_for_scene(
        scene_date=scene_date,
        semantic_domain=semantic_domain,
        group_raster=group_raster,
        group_lut_records=group_lut_records,
        group_profile=group_profile,
        out_scene_dir=out_scene_dir,
    )

    group_df.to_csv(out_scene_dir / "group_scene_summary.csv", index=False)

    lookup_df = pd.DataFrame(lookup_logs)
    if not lookup_df.empty:
        enriched = []
        for rec in lookup_logs:
            row = env_lookup.get((str(rec["group_code"]), str(rec["index"]), str(rec["used_bin"])))
            if row is None:
                row = env[(env["group_code"] == rec["group_code"]) & (env["index"] == rec["index"]) & (env["doy_bin_label"] == rec["used_bin"])].iloc[0]
            enriched.append({
                **rec,
                "env_q_low": row[ENVELOPE_LOW_COL],
                "env_q_high": row[ENVELOPE_HIGH_COL],
                "operational_width": _row_value(row, "operational_width", row[ENVELOPE_HIGH_COL] - row[ENVELOPE_LOW_COL]),
                "n_dates": _row_value(row, "n_dates"),
                "n_unique_dates": _row_value(row, "n_unique_dates", _row_value(row, "n_dates")),
                "n_scene_records": _row_value(row, "n_scene_records"),
                "support_pixels_total": _row_value(row, "support_pixels_total"),
                "envelope_confidence": confidence_from_row(row),
                "envelope_confidence_code": confidence_code_from_row(row),
                "low_support_flag": _as_bool(_row_value(row, "low_support_flag", False)),
                "low_temporal_support_flag": _as_bool(_row_value(row, "low_temporal_support_flag", False)),
                "support_pixels_total_low_flag": _as_bool(_row_value(row, "support_pixels_total_low_flag", False)),
                "confidence_reason": _row_value(row, "confidence_reason", ""),
            })
        lookup_df = pd.DataFrame(enriched)
        lookup_df.to_csv(out_scene_dir / "group_lookup_used.csv", index=False)

    n_domain = int(semantic_domain.sum())
    scene_summary = {
        "scene": scene,
        "scene_key": scene_key,
        "date": scene_date.date().isoformat(),
        "doy": scene_doy,
        "doy_bin_label": bin_label,
        "n_grouped_valid_px": n_domain,
        "keep_px": int(keep.sum()),
        "drop_px": int(drop.sum()),
        "keep_pct": float(100.0 * keep.sum() / n_domain) if n_domain else np.nan,
        "drop_pct": float(100.0 * drop.sum() / n_domain) if n_domain else np.nan,
        "n_group_ids_used": int(group_df["group_id"].nunique()) if not group_df.empty else 0,
        "n_fallback_lookups": int(lookup_df["fallback_used"].sum()) if not lookup_df.empty else 0,
        "n_total_lookups": int(len(lookup_df)),
        "scl_available": bool(scene_row.get("scl_available", False)),
        "scl_used": bool(scene_row.get("scl_used", False)),
        "processed_from_phase3_cache": True,
        "cache_clear_mask_path": str(scene_row["clear_mask_path"]),
        "cache_index_stack_path": str(scene_row["index_stack_path"]),
        **s1_scene_meta,
        "write_anomaly_score": WRITE_ANOMALY_SCORE,
        "write_envelope_confidence_mask": WRITE_ENVELOPE_CONFIDENCE_MASK,
        "n_high_confidence_lookups": int((lookup_df["envelope_confidence"] == "high").sum()) if not lookup_df.empty and "envelope_confidence" in lookup_df.columns else 0,
        "n_medium_confidence_lookups": int((lookup_df["envelope_confidence"] == "medium").sum()) if not lookup_df.empty and "envelope_confidence" in lookup_df.columns else 0,
        "n_low_confidence_lookups": int((lookup_df["envelope_confidence"] == "low").sum()) if not lookup_df.empty and "envelope_confidence" in lookup_df.columns else 0,
        "n_missing_or_unknown_confidence_lookups": int(lookup_df["envelope_confidence"].isin(["missing", "unknown"]).sum()) if not lookup_df.empty and "envelope_confidence" in lookup_df.columns else 0,
        "n_groups_low_core_confidence": int((group_df["core_envelope_confidence"] == "low").sum()) if not group_df.empty and "core_envelope_confidence" in group_df.columns else 0,
        "mean_anomaly_score": float(np.nanmean(anomaly_score[semantic_domain])) if anomaly_score is not None and n_domain else np.nan,
        "core_indices": ",".join(CORE_INDICES),
        "keep_votes_required": KEEP_VOTES_REQUIRED,
    }
    return scene_summary, group_df, lookup_df


