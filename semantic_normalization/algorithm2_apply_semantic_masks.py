def main() -> None:
    t0 = time.time()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    require_cache_file(CACHE_ROOT / "preprocessing_manifest.json")
    manifest = read_json(CACHE_ROOT / "preprocessing_manifest.json")

    inv_all = load_scene_inventory_with_recommendations()
    target_inv, eligibility_df = filter_inventory_by_recommendation(inv_all)
    target_inv, eligibility_df = deduplicate_inventory_by_date(target_inv, eligibility_df)
    eligibility_df.to_csv(OUTPUT_DIR / "scene_eligibility_filter.csv", index=False)
    if target_inv.empty:
        raise RuntimeError(
            f"Scene filter policy {ENVELOPE_RUN!r} excluded all target scenes. "
            f"See {OUTPUT_DIR / 'scene_eligibility_filter.csv'}"
        )

    env = load_envelopes()
    env_lookup = build_envelope_lookup(env)
    group_raster, group_profile = read_int_raster(require_cache_file(CACHE_ROOT / "all_fmu_group_id.tif"))
    group_lut = pd.read_csv(require_cache_file(CACHE_ROOT / "group_lut_all_fmu.csv"))

    log(f"Selected envelope run: {ENVELOPE_RUN}")
    log(f"Phase 3 cache root: {CACHE_ROOT}")
    log(f"Cache scene count: {len(inv_all)}")
    log(f"Target scenes after filter/date deduplication: {len(target_inv)}")

    scene_rows = []
    group_rows_all = []
    lookup_rows_all = []
    for i, (_, row) in enumerate(target_inv.sort_values(["date", "scene"]).iterrows(), start=1):
        log(f"Processing cached scene [{i}/{len(target_inv)}] {row['scene']} ...")
        scene_summary, group_df, lookup_df = process_cached_scene(row, env, env_lookup, group_raster, group_profile, group_lut)
        scene_rows.append(scene_summary)
        if not group_df.empty:
            group_rows_all.append(group_df)
        if not lookup_df.empty:
            tmp = lookup_df.copy()
            tmp.insert(0, "scene", row["scene"])
            lookup_rows_all.append(tmp)

    pd.DataFrame(scene_rows).sort_values(["date", "scene"]).to_csv(OUTPUT_DIR / "scene_summary.csv", index=False)
    if group_rows_all:
        pd.concat(group_rows_all, ignore_index=True).to_csv(OUTPUT_DIR / "group_scene_summary_all.csv", index=False)
    if lookup_rows_all:
        pd.concat(lookup_rows_all, ignore_index=True).to_csv(OUTPUT_DIR / "lookup_trace_all.csv", index=False)

    readme = OUTPUT_DIR / "README.txt"
    readme.write_text(
        "Algorithm #2 Phase 5 semantic keep/drop masking using optical envelopes plus optional Sentinel-1 descriptor summaries.\n\n"
        f"Phase 3 cache root: {CACHE_ROOT}\n"
        f"Cache zip count: {manifest.get('zip_count')}\n"
        f"Envelope source: {ENVELOPE_SOURCE.name}\n"
        f"Target scene count before scene filter: {len(inv_all)}\n"
        f"Target scene count after scene filter/date deduplication: {len(target_inv)}\n"
        f"Scene filter policy: {ENVELOPE_RUN}; allowed recommendations: {';'.join(sorted(allowed_recommendations_for_envelope_run(ENVELOPE_RUN)))}\n"
        f"Deduplicate scenes by acquisition date: {DEDUPLICATE_TARGET_SCENES_BY_DATE}\n"
        "Input rasters were read from Phase 3 cache, not directly from Sentinel-2 ZIP scenes.\n"
        f"Sentinel-1 descriptor summaries enabled: {ENABLE_S1_DESCRIPTOR_SUMMARIES}\n"
        f"Sentinel-1 cache root: {S1_CACHE_ROOT}\n"
        f"Sentinel-1 maximum date offset: {S1_MAX_ABS_DATE_OFFSET_DAYS} days\n"
        f"Core indices: {', '.join(CORE_INDICES)}\n"
        f"Optional indices: {', '.join(OPTIONAL_INDICES) if OPTIONAL_INDICES else 'None'}\n"
        f"Keep rule: keep if at least {KEEP_VOTES_REQUIRED} of {len(CORE_INDICES)} core indices fall inside the healthy envelope\n"
        f"Envelope columns used: {ENVELOPE_LOW_COL}, {ENVELOPE_HIGH_COL}\n"
        f"Write anomaly-score raster: {WRITE_ANOMALY_SCORE}; nodata = {ANOMALY_SCORE_NODATA}\n"
        f"Write envelope-confidence mask: {WRITE_ENVELOPE_CONFIDENCE_MASK}; values = {ENVELOPE_CONFIDENCE_VALUES}\n"
        "Phase 4 confidence/anomaly outputs are diagnostic and do not change the default keep/drop rule.\n"
        f"DOY bin width: {DOY_BIN_WIDTH}\n"
        f"Fallback: {'nearest DOY bin' if USE_NEAREST_BIN_FALLBACK else 'none'}\n"
        "Valid domain: cached clear pixels inside grouped FMU polygons with finite core indices.\n",
        encoding="utf-8",
    )
    log(f"Done in {time.time() - t0:.1f}s. Outputs in {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
