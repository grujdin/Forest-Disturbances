def allowed_scene_recommendations(mode: str) -> set[str]:
    mode = mode.lower().strip()
    if mode == "none":
        return {"keep", "caution", "blacklist"}
    if mode == "blacklist":
        return {"keep", "caution"}
    if mode == "blacklist_and_caution":
        return {"keep"}
    raise ValueError(f"Unsupported SCENE_FILTER_MODE: {mode!r}")


def _norm_codes(values) -> List[str]:
    out = []
    for value in values:
        if pd.isna(value):
            continue
        s = str(value).strip()
        if s and s.lower() != "nan":
            out.append(s)
    return sorted(set(out))


def emit_group_code_checks_cache(stable_lut: pd.DataFrame, env_df: pd.DataFrame) -> None:
    """Write group-code consistency diagnostics using cache group LUTs."""
    try:
        xls = pd.ExcelFile(GROUP_WORKBOOK)
        sheet = GROUP_SHEET if GROUP_SHEET in xls.sheet_names else xls.sheet_names[0]
        workbook_attrs = pd.read_excel(GROUP_WORKBOOK, sheet_name=sheet)
        workbook_raw_codes = _norm_codes(workbook_attrs.get(GROUP_CODE_FIELD, pd.Series(dtype=object)))
    except Exception as exc:
        warnings.warn(f"Could not load workbook group-code diagnostics: {exc}")
        workbook_raw_codes = []

    workbook_non_excluded_codes = [c for c in workbook_raw_codes if c not in EXCLUDE_GROUP_CODES]
    support_group_codes = _norm_codes(stable_lut.get("group_code", pd.Series(dtype=object)))
    raster_group_codes = support_group_codes
    envelope_group_codes = _norm_codes(env_df.get("group_code", pd.Series(dtype=object)))

    workbook_not_used_after_filters = [c for c in workbook_non_excluded_codes if c not in support_group_codes]
    missing_in_envelopes = [c for c in support_group_codes if c not in envelope_group_codes]
    extra_in_envelopes = [c for c in envelope_group_codes if c not in support_group_codes]

    log(f"Workbook group codes (raw): {workbook_raw_codes}")
    log(f"Workbook group codes (non-excluded): {workbook_non_excluded_codes}")
    log(f"Support group codes after stable/exclusion filters: {support_group_codes}")
    log(f"Rasterized group codes: {raster_group_codes}")
    log(f"Generated envelope group codes: {envelope_group_codes}")

    if workbook_not_used_after_filters:
        log("Info: workbook codes not used after stable/exclusion filters: " + ", ".join(workbook_not_used_after_filters))

    report_rows = []
    all_codes = sorted(set(workbook_raw_codes) | set(workbook_non_excluded_codes) | set(support_group_codes) | set(envelope_group_codes))
    for code in all_codes:
        report_rows.append({
            "group_code": code,
            "in_workbook_raw": code in workbook_raw_codes,
            "in_workbook_non_excluded": code in workbook_non_excluded_codes,
            "in_support_after_filters": code in support_group_codes,
            "in_raster_group_table": code in raster_group_codes,
            "in_generated_envelopes": code in envelope_group_codes,
        })
    pd.DataFrame(report_rows).to_csv(OUTPUT_DIR / "group_code_check_report.csv", index=False)

    summary_lines = [
        f"Workbook group codes (raw): {', '.join(workbook_raw_codes) if workbook_raw_codes else '(none)'}",
        f"Workbook group codes (non-excluded): {', '.join(workbook_non_excluded_codes) if workbook_non_excluded_codes else '(none)'}",
        f"Support group codes after stable/exclusion filters: {', '.join(support_group_codes) if support_group_codes else '(none)'}",
        f"Rasterized group codes: {', '.join(raster_group_codes) if raster_group_codes else '(none)'}",
        f"Generated envelope group codes: {', '.join(envelope_group_codes) if envelope_group_codes else '(none)'}",
    ]
    if missing_in_envelopes:
        msg = "WARNING: support group codes missing from generated envelopes: " + ", ".join(missing_in_envelopes)
        warnings.warn(msg)
        log(msg)
        summary_lines.append(msg)
    else:
        ok_msg = "Support group codes and generated envelope group codes match."
        log(ok_msg)
        summary_lines.append(ok_msg)
    if extra_in_envelopes:
        msg = "WARNING: envelope group codes not present in support groups: " + ", ".join(extra_in_envelopes)
        warnings.warn(msg)
        log(msg)
        summary_lines.append(msg)
    (OUTPUT_DIR / "group_code_check_summary.txt").write_text("\n".join(summary_lines), encoding="utf-8")


def collapse_duplicate_date_rows(date_df: pd.DataFrame) -> pd.DataFrame:
    group_cols = [
        "date", "year", "month", "day", "doy", "doy_bin_label", "doy_bin_center",
        "group_id", "group_code", "group_label", "index",
    ]
    agg = {
        "zip_file": lambda x: ";".join(sorted(set(map(str, x)))),
        "n_valid_pixels": "sum",
        "date_min": "min",
        "date_q10": "median",
        "date_median": "median",
        "date_q90": "median",
        "date_max": "max",
        "date_mean": "mean",
    }
    out = date_df.groupby(group_cols, dropna=False, as_index=False).agg(agg)
    counts = date_df.groupby(group_cols, dropna=False)["zip_file"].count().reset_index(name="n_scene_records")
    out = out.merge(counts, on=group_cols, how="left")
    ordered = [
        "zip_file", "n_scene_records", "date", "year", "month", "day", "doy",
        "doy_bin_label", "doy_bin_center", "group_id", "group_code", "group_label",
        "index", "n_valid_pixels", "date_min", "date_q10", "date_median",
        "date_q90", "date_max", "date_mean",
    ]
    return out[ordered].sort_values(["group_code", "index", "date"]).reset_index(drop=True)


def envelope_confidence_code(n_unique_dates: int, support_pixels_total: int) -> int:
    """Return 3=high, 2=medium, 1=low, 0=missing envelope support."""
    try:
        n_unique_dates = int(n_unique_dates)
    except Exception:
        n_unique_dates = 0
    try:
        support_pixels_total = int(support_pixels_total)
    except Exception:
        support_pixels_total = 0

    if n_unique_dates <= 0 or support_pixels_total <= 0:
        return 0
    if n_unique_dates >= ENVELOPE_CONFIDENCE_HIGH_MIN_UNIQUE_DATES:
        return 3
    if (
        n_unique_dates >= ENVELOPE_CONFIDENCE_MEDIUM_MIN_UNIQUE_DATES
        and support_pixels_total >= MIN_SUPPORT_PIXELS_TOTAL_FOR_MEDIUM_CONFIDENCE
    ):
        return 2
    return 1


def envelope_confidence_label(code: int) -> str:
    """Return a text label for the envelope-confidence code."""
    return {3: "high", 2: "medium", 1: "low", 0: "missing"}.get(int(code), "unknown")


def write_envelope_quality_tables(env_df: pd.DataFrame) -> None:
    """Write Phase 4 support/confidence diagnostics for envelope rows."""
    if not WRITE_ENVELOPE_QUALITY_TABLES or env_df.empty:
        return

    quality_cols = [
        "group_code", "group_label", "index", "doy_bin_label", "doy_bin_center",
        "n_unique_dates", "n_scene_records", "support_pixels_total",
        "support_pixels_per_date_min", "support_pixels_per_date_mean",
        "env_q_width", "operational_width",
        "envelope_confidence", "envelope_confidence_code",
        "low_support_flag", "low_temporal_support_flag", "support_pixels_total_low_flag",
    ]
    cols = [c for c in quality_cols if c in env_df.columns]
    env_df[cols].to_csv(OUTPUT_DIR / "doy_bin_envelope_quality.csv", index=False)

    summary = (
        env_df.groupby(["envelope_confidence", "envelope_confidence_code"], dropna=False)
        .size()
        .reset_index(name="n_envelope_rows")
        .sort_values(["envelope_confidence_code", "envelope_confidence"], ascending=[False, True])
    )
    summary.to_csv(OUTPUT_DIR / "doy_bin_envelope_quality_summary.csv", index=False)

    by_doy = (
        env_df.groupby(["doy_bin_label", "envelope_confidence"], dropna=False)
        .size()
        .reset_index(name="n_envelope_rows")
        .sort_values(["doy_bin_label", "envelope_confidence"])
    )
    by_doy.to_csv(OUTPUT_DIR / "doy_bin_envelope_quality_by_doy_bin.csv", index=False)

    by_group_index = (
        env_df.groupby(["group_code", "index"], dropna=False)
        .agg(
            n_envelope_rows=("envelope_confidence_code", "size"),
            min_confidence_code=("envelope_confidence_code", "min"),
            low_confidence_rows=("low_support_flag", "sum"),
            min_unique_dates=("n_unique_dates", "min"),
            median_unique_dates=("n_unique_dates", "median"),
            max_unique_dates=("n_unique_dates", "max"),
        )
        .reset_index()
        .sort_values(["group_code", "index"])
    )
    by_group_index.to_csv(OUTPUT_DIR / "doy_bin_envelope_quality_by_group_index.csv", index=False)


