def _scatter_or_range_by_year(ax, pts: pd.DataFrame) -> None:
    """Plot date-level points, optionally colored and connected by year."""
    if pts.empty or not SHOW_DATE_MEDIAN_POINTS:
        return

    pts = pts.copy()
    pts["date"] = pd.to_datetime(pts["date"], errors="coerce")
    pts = pts[pts["date"].notna()].copy()
    if pts.empty:
        return
    pts["year"] = pts["date"].dt.year.astype(int)

    def _draw_ranges(data: pd.DataFrame, color=None) -> None:
        x = data["doy"].to_numpy(dtype=float)
        if SHOW_DATE_MIN_MAX_RANGES and {"date_min", "date_max"}.issubset(data.columns):
            ax.vlines(
                x,
                data["date_min"].to_numpy(dtype=float),
                data["date_max"].to_numpy(dtype=float),
                colors=color,
                linewidth=DATE_RANGE_LINEWIDTH,
                alpha=DATE_RANGE_ALPHA,
                label="_nolegend_",
            )
        if SHOW_DATE_Q10_Q90_RANGES and {"date_q10", "date_q90"}.issubset(data.columns):
            ax.vlines(
                x,
                data["date_q10"].to_numpy(dtype=float),
                data["date_q90"].to_numpy(dtype=float),
                colors=color,
                linewidth=max(DATE_RANGE_LINEWIDTH, 1.0),
                alpha=min(DATE_RANGE_ALPHA + 0.15, 1.0),
                label="_nolegend_",
            )

    if COLOR_POINTS_BY_YEAR:
        years = sorted(pts["year"].dropna().unique().tolist())
        cmap = plt.get_cmap(YEAR_COLORMAP, max(len(years), 1))
        year_to_color = {yr: cmap(i) for i, yr in enumerate(years)}

        for yr in years:
            ysub = pts[pts["year"] == yr].sort_values("doy")
            color = year_to_color[yr]
            _draw_ranges(ysub, color=color)
            ax.scatter(
                ysub["doy"],
                ysub["date_median"],
                s=SCATTER_SIZE,
                alpha=SCATTER_ALPHA,
                color=color,
                label=f"{yr} date medians",
            )
            if CONNECT_POINTS_WITHIN_YEAR and len(ysub) >= 2:
                ax.plot(
                    ysub["doy"],
                    ysub["date_median"],
                    linestyle=":",
                    linewidth=YEAR_LINEWIDTH,
                    alpha=min(SCATTER_ALPHA + 0.05, 1.0),
                    color=color,
                    label="_nolegend_",
                )
    else:
        pts = pts.sort_values("doy")
        _draw_ranges(pts, color=None)
        ax.scatter(
            pts["doy"],
            pts["date_median"],
            s=SCATTER_SIZE,
            alpha=SCATTER_ALPHA,
            label="Date medians",
        )


def write_optional_plots(env_df: pd.DataFrame, date_df_for_plot: pd.DataFrame) -> None:
    """Write envelope plots with the original selectable display capabilities restored.

    Each plot is generated for one analytical group and one spectral index.
    The display can include the envelope band, envelope median, min/max date-median
    curves, operational q10/q90 bounds, pixel min/max bounds, date-level points
    colored by year, and optional within-year connections.
    """
    if not MAKE_PLOTS:
        log("Finished envelope aggregation; skipping plot generation (MAKE_PLOTS=False)")
        pd.DataFrame([_plot_options_dict()]).to_csv(OUTPUT_DIR / "plot_options_used.csv", index=False)
        return

    log("Finished envelope aggregation; starting plots")
    plots_dir = _prepare_plots_dir()
    n_plots = 0

    for (group_code, group_label, index_name), sub in env_df.groupby(["group_code", "group_label", "index"], dropna=False):
        sub = sub.sort_values("doy_bin_center")
        if len(sub) < MIN_DATES_PER_BIN_FOR_PLOT:
            continue

        x = sub["doy_bin_center"].to_numpy(dtype=float)
        fig, ax = plt.subplots(figsize=PLOT_FIGSIZE)

        if SHOW_LOW_CONFIDENCE_BIN_MARKERS and "envelope_confidence" in sub.columns:
            low_conf = sub[sub["envelope_confidence"].astype(str).str.lower().isin(["low", "missing"])]
            first_marker = True
            for xc in low_conf["doy_bin_center"].to_numpy(dtype=float):
                ax.axvline(
                    xc,
                    linestyle=":",
                    linewidth=0.8,
                    alpha=0.20,
                    label="Low-confidence DOY bin" if first_marker else "_nolegend_",
                )
                first_marker = False

        if SHOW_ENVELOPE_BAND:
            env_low = sub["env_q_low"].to_numpy(dtype=float)
            env_high = sub["env_q_high"].to_numpy(dtype=float)
            ax.fill_between(
                x,
                env_low,
                env_high,
                alpha=0.20,
                label=f"Envelope q{int(ENV_Q_LOW * 100)}–q{int(ENV_Q_HIGH * 100)}",
            )

        if SHOW_ENVELOPE_MEDIAN:
            ax.plot(
                x,
                sub["env_q_med"].to_numpy(dtype=float),
                linewidth=2.0,
                label="Envelope median (q50)",
            )

        if SHOW_CURVE_MIN_MAX and {"curve_min", "curve_max"}.issubset(sub.columns):
            ax.plot(
                x,
                sub["curve_min"].to_numpy(dtype=float),
                linestyle="--",
                linewidth=1.3,
                label="Min of date medians",
            )
            ax.plot(
                x,
                sub["curve_max"].to_numpy(dtype=float),
                linestyle="--",
                linewidth=1.3,
                label="Max of date medians",
            )

        if SHOW_OPERATIONAL_Q10_Q90 and {"median_of_date_q10", "median_of_date_q90"}.issubset(sub.columns):
            ax.plot(
                x,
                sub["median_of_date_q10"].to_numpy(dtype=float),
                linestyle="-.",
                linewidth=1.1,
                label="Median of date q10",
            )
            ax.plot(
                x,
                sub["median_of_date_q90"].to_numpy(dtype=float),
                linestyle="-.",
                linewidth=1.1,
                label="Median of date q90",
            )

        if SHOW_PIXEL_MIN_MAX_RANGE and {"min_of_date_min", "max_of_date_max"}.issubset(sub.columns):
            ax.plot(
                x,
                sub["min_of_date_min"].to_numpy(dtype=float),
                linestyle=":",
                linewidth=1.0,
                alpha=0.75,
                label="Min of date minima",
            )
            ax.plot(
                x,
                sub["max_of_date_max"].to_numpy(dtype=float),
                linestyle=":",
                linewidth=1.0,
                alpha=0.75,
                label="Max of date maxima",
            )

