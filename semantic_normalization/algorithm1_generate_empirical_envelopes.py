def resolve_s1_descriptors_for_envelopes(s1_inventory: pd.DataFrame) -> List[str]:
    """Resolve Sentinel-1 descriptors to summarize.

    In Phase 5 v3 the S1 cache records descriptor_bands_available per scene.
    With S1_DESCRIPTOR_BANDS_FOR_ENVELOPES = "auto", only descriptors with
    actual finite data are used. Binary validity and unavailable VV descriptors
    are excluded.
    """
    cfg = S1_DESCRIPTOR_BANDS_FOR_ENVELOPES
    if isinstance(cfg, str) and cfg.lower().strip() == "auto":
        found = []
        if "descriptor_bands_available" in s1_inventory.columns:
            for txt in s1_inventory["descriptor_bands_available"].fillna("").astype(str):
                for name in [x.strip() for x in txt.split(",") if x.strip()]:
                    if name not in found and name not in S1_DESCRIPTOR_EXCLUDE_FROM_ENVELOPES:
                        found.append(name)
        if not found:
            # Backward compatible fallback for older S1 caches.
            found = [
                name for name in S1_DESCRIPTOR_BANDS
                if name not in S1_DESCRIPTOR_EXCLUDE_FROM_ENVELOPES
            ]
        return found
    return [str(x) for x in cfg if str(x) not in S1_DESCRIPTOR_EXCLUDE_FROM_ENVELOPES]


def write_s1_descriptor_envelopes(stable_group_raster: np.ndarray, group_profile: dict, stable_lut: pd.DataFrame) -> pd.DataFrame:
    """Generate separate Sentinel-1 descriptor envelopes from the Phase 5 S1 cache.

    The output uses the same column logic as the optical envelope table, but is
    written to s1_doy_bin_envelopes.csv. The main optical doy_bin_envelopes.csv
    remains unchanged for Algorithm #2 compatibility.
    """
    if not INCLUDE_S1_DESCRIPTOR_ENVELOPES:
        return pd.DataFrame()
    if not S1_CACHE_ROOT.exists():
        log(f"Sentinel-1 cache not found; skipping S1 descriptor envelopes: {S1_CACHE_ROOT}")
        return pd.DataFrame()
    s1_inv = load_s1_inventory(S1_CACHE_ROOT)
    if s1_inv.empty:
        log("Sentinel-1 inventory is empty; skipping S1 descriptor envelopes")
        return pd.DataFrame()

    available = s1_inv[s1_inv.get("cache_status", "").astype(str).str.lower().isin(["created", "rebuilt", "existing"])] if "cache_status" in s1_inv.columns else s1_inv
    if available.empty:
        log("No valid Sentinel-1 cached scenes available; skipping S1 descriptor envelopes")
        return pd.DataFrame()

    s1_descriptors_for_envelopes = resolve_s1_descriptors_for_envelopes(available)
    log(f"Sentinel-1 descriptors selected for envelope summarization: {', '.join(s1_descriptors_for_envelopes) if s1_descriptors_for_envelopes else 'none'}")

    support_domain = stable_group_raster > 0
    group_records = stable_lut[["group_id", "group_code", "group_label"]].drop_duplicates().itertuples(index=False)
    group_records = list(group_records)
    s1_rows: List[dict] = []

    for i_scene, row in enumerate(available.sort_values(["date", "scene"]).itertuples(index=False), start=1):
        scene = str(getattr(row, "scene"))
        s1_date = pd.Timestamp(getattr(row, "date"))
        stack_path = Path(getattr(row, "s1_stack_path"))
        valid_path = Path(getattr(row, "s1_valid_mask_path"))
        if not stack_path.exists() or not valid_path.exists():
            continue
        try:
            try:
                stack, stack_profile = read_float32_stack(stack_path, expected_names=S1_DESCRIPTOR_BANDS)
            except Exception:
                stack, stack_profile = read_float32_stack(stack_path)
            valid_arr, valid_profile = read_uint8_raster(valid_path)
            if not same_grid(stack_profile, group_profile) or not same_grid(valid_profile, group_profile):
                raise RuntimeError(f"S1 stack grid does not match stable support group raster for {scene}")
            valid_mask = (valid_arr == 1) & support_domain
            for group_id, group_code, group_label in group_records:
                group_mask = valid_mask & (stable_group_raster == int(group_id))
                if int(group_mask.sum()) < S1_MIN_PIXELS_PER_GROUP_DATE:
                    continue
                for descriptor in s1_descriptors_for_envelopes:
                    arr = stack.get(descriptor)
                    if arr is None:
                        continue
                    vals = arr[group_mask]
                    vals = vals[np.isfinite(vals)]
                    if vals.size < S1_MIN_PIXELS_PER_GROUP_DATE:
                        continue
                    doy = int(s1_date.dayofyear)
                    s1_rows.append({
                        "sensor": "S1",
                        "zip_file": scene,
                        "date": s1_date.date().isoformat(),
                        "year": int(s1_date.year),
                        "month": int(s1_date.month),
                        "day": int(s1_date.day),
                        "doy": doy,
                        "doy_bin_label": doy_bin_label(doy, DOY_BIN_WIDTH),
                        "doy_bin_center": doy_bin_center(doy, DOY_BIN_WIDTH),
                        "group_id": int(group_id),
                        "group_code": group_code,
                        "group_label": group_label,
                        "index": descriptor,
                        "descriptor": descriptor,
                        "n_valid_pixels": int(vals.size),
                        "date_min": float(np.min(vals)),
                        "date_q10": float(np.quantile(vals, 0.10)),
                        "date_median": float(np.median(vals)),
                        "date_q90": float(np.quantile(vals, 0.90)),
                        "date_max": float(np.max(vals)),
                        "date_mean": float(np.mean(vals)),
                    })
        except Exception as exc:
            log(f"WARNING: could not summarize S1 descriptors for {scene}: {exc}")
            continue
        log(f"[S1 {i_scene}/{len(available)}] summarized {scene}; cumulative S1 rows = {len(s1_rows)}")

    if not s1_rows:
        log("No Sentinel-1 descriptor rows were generated")
        return pd.DataFrame()

    s1_date_df = pd.DataFrame(s1_rows).sort_values(["group_code", "index", "date", "zip_file"]).reset_index(drop=True)
    s1_date_df.to_csv(OUTPUT_DIR / "s1_date_group_descriptor_medians.csv", index=False)
    s1_unique_df = collapse_duplicate_date_rows(s1_date_df)
    s1_unique_df["sensor"] = "S1"
    s1_unique_df["descriptor"] = s1_unique_df["index"]
    s1_unique_df.to_csv(OUTPUT_DIR / "s1_date_group_descriptor_medians_by_unique_date.csv", index=False)

    env_rows = []
    group_cols = ["group_code", "group_label", "index", "doy_bin_label", "doy_bin_center"]
    for keys, sub in s1_unique_df.groupby(group_cols, dropna=False):
        group_code, group_label, descriptor, bin_label, bin_center = keys
        medians = sub["date_median"].to_numpy(dtype=float)
        q10s = sub["date_q10"].to_numpy(dtype=float)
        q90s = sub["date_q90"].to_numpy(dtype=float)
        mins = sub["date_min"].to_numpy(dtype=float)
        maxs = sub["date_max"].to_numpy(dtype=float)
        n_unique_dates = int(sub["date"].nunique())
        n_scene_records = int(sub.get("n_scene_records", pd.Series([1] * len(sub), index=sub.index)).sum())
        support_pixels_total = int(sub["n_valid_pixels"].sum())
        support_pixels_per_date_min = int(sub["n_valid_pixels"].min())
        support_pixels_per_date_mean = float(sub["n_valid_pixels"].mean())
        env_q_low = float(np.quantile(medians, ENV_Q_LOW))
        env_q_med = float(np.quantile(medians, 0.50))
        env_q_high = float(np.quantile(medians, ENV_Q_HIGH))
        median_of_date_q10 = float(np.median(q10s))
        median_of_date_q90 = float(np.median(q90s))
        confidence_code = envelope_confidence_code(n_unique_dates, support_pixels_total)
        env_rows.append({
            "sensor": "S1",
            "group_code": group_code,
            "group_label": group_label,
            "index": descriptor,
            "descriptor": descriptor,
            "doy_bin_label": bin_label,
            "doy_bin_center": int(bin_center),
            "n_dates": n_unique_dates,
            "n_unique_dates": n_unique_dates,
            "n_scene_records": n_scene_records,
            "support_pixels_total": support_pixels_total,
            "support_pixels_per_date_min": support_pixels_per_date_min,
            "support_pixels_per_date_mean": support_pixels_per_date_mean,
            "env_q_low": env_q_low,
            "env_q_med": env_q_med,
            "env_q_high": env_q_high,
            "env_q_width": float(env_q_high - env_q_low),
            "curve_min": float(np.min(medians)),
            "curve_med": float(np.median(medians)),
            "curve_max": float(np.max(medians)),
            "median_of_date_q10": median_of_date_q10,
            "median_of_date_q90": median_of_date_q90,
            "operational_width": float(median_of_date_q90 - median_of_date_q10),
            "min_of_date_min": float(np.min(mins)),
            "max_of_date_max": float(np.max(maxs)),
            "envelope_confidence": envelope_confidence_label(confidence_code),
            "envelope_confidence_code": confidence_code,
            "low_support_flag": bool(confidence_code < 2),
            "low_temporal_support_flag": bool(n_unique_dates < ENVELOPE_CONFIDENCE_MEDIUM_MIN_UNIQUE_DATES),
            "support_pixels_total_low_flag": bool(support_pixels_total < MIN_SUPPORT_PIXELS_TOTAL_FOR_MEDIUM_CONFIDENCE),
        })
    s1_env = pd.DataFrame(env_rows).sort_values(["group_code", "index", "doy_bin_center"]).reset_index(drop=True)
    s1_env.to_csv(OUTPUT_DIR / "s1_doy_bin_envelopes.csv", index=False)

    s1_quality = (
        s1_env.groupby(["envelope_confidence", "envelope_confidence_code"], dropna=False)
        .size().reset_index(name="n_s1_envelope_rows")
        .sort_values("envelope_confidence_code")
    )
    s1_quality.to_csv(OUTPUT_DIR / "s1_doy_bin_envelope_quality_summary.csv", index=False)
    coverage = (
        s1_unique_df.groupby(["group_code", "index"])
        .agg(n_dates=("date", "nunique"), n_scene_records=("n_scene_records", "sum"), min_doy=("doy", "min"), max_doy=("doy", "max"))
        .reset_index().sort_values(["group_code", "index"])
    )
    coverage.to_csv(OUTPUT_DIR / "s1_group_descriptor_date_coverage.csv", index=False)
    log(f"Wrote Sentinel-1 descriptor envelopes: {len(s1_env)} rows")
    return s1_env

